void handle_sigterm(int sig){
    exit(EXIT_FAILURE);
}

void flush_output(){
    fflush(stdout);
    fflush(stderr);
}

int main() {
    signal(SIGTERM, handle_sigterm);
    atexit(flush_output);

    int sock_fd;
    struct sockaddr_in server_addr, client_addr;
    unsigned char buffer[BUFFER_SIZE];
    unsigned char *answer;
    size_t answer_size;
    bzero(&server_addr, sizeof(server_addr));
    
    sock_fd = socket(AF_INET, SOCK_DGRAM, 0);
    if (sock_fd < 0) {
        perror("Socket creation failed");
        exit(EXIT_FAILURE);
    }

    printf("Socket successfully created\n");

    server_addr.sin_family = AF_INET;
    server_addr.sin_addr.s_addr = inet_addr("127.0.0.2");
    server_addr.sin_port = htons(DNS_PORT);

    if (bind(sock_fd, (struct sockaddr *)&server_addr, sizeof(server_addr)) < 0) {
        perror("Bind failed");
        close(sock_fd);
        exit(EXIT_FAILURE);
    }

    printf("Binding was successful\n");

    printf("DNS mock server running on port %d...\n", DNS_PORT);

    while (1) {
        socklen_t addr_len = sizeof(client_addr);
        int recv_len = recvfrom(sock_fd, buffer, BUFFER_SIZE, 0, (struct sockaddr *)&client_addr, &addr_len);

        printf("Received message length: %d\nMessage:\n", recv_len);

        uint8_t *data2 = (uint8_t *) buffer;
        for(int i = 0; i < recv_len; i++){
            printf("0x%02X ", data2[i]);
        }
        printf("\n");

        const uint16_t *data = (const uint16_t *) buffer;
        ldns_buffer *ldns_buffer;
        ldns_pkt *pkt;
        ldns_buffer = ldns_buffer_new(BUFFER_SIZE);
        // write data in an ldnsBuffer
        ldns_buffer_write(ldns_buffer, data, recv_len);
        // ldnsBuffer in wire format can be converted in a DNS packet
        ldns_buffer2pkt_wire(&pkt, ldns_buffer);
        switch (ldns_rr_get_type(ldns_rr_list_rr(ldns_pkt_question(pkt), 0))) {
            case LDNS_RR_TYPE_A:
                answer = A_answer;
                answer_size = sizeof(A_answer);
                break;
            case LDNS_RR_TYPE_AAAA:
                answer = AAAA_answer;
                answer_size = sizeof(AAAA_answer);
                break;
            case LDNS_RR_TYPE_PTR:
                answer = PTR_answer;
                answer_size = sizeof(PTR_answer);
                break;
            case LDNS_RR_TYPE_TXT:
                answer = TXT_answer;
                answer_size = sizeof(TXT_answer);
                break;
            case LDNS_RR_TYPE_MX:
                answer = MX_answer;
                answer_size = sizeof(MX_answer);
                break;
            case LDNS_RR_TYPE_NS:
                answer = NS_answer;
                answer_size = sizeof(NS_answer);
                break;
            default:
                printf("Unexpected RR type! (%s)\n", ldns_rr_type2str(ldns_rr_get_type(ldns_rr_list_rr(ldns_pkt_question(pkt), 0))));
                close(sock_fd);
                exit(EXIT_FAILURE);
        }

        answer[0] = data2[0];
        answer[1] = data2[1];

        printf("Answer message:\n");

        uint8_t *data3 = (uint8_t *) answer;
        for(size_t i = 0; i < answer_size; i++){
            printf("0x%02X ", data3[i]);
        }
        printf("\n");

        if (recv_len > 0) {
            printf("Sending answer\n");
            sendto(sock_fd, answer, answer_size, 0, (struct sockaddr *)&client_addr, addr_len);
        }
    }

    close(sock_fd);
    return 0;
}

